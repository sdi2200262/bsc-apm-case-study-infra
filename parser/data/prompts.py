"""Predicates that classify the shape of a Claude Code user record.

A ``user`` record can carry the user's own input or one of several kinds
of platform bookkeeping written around it: the local-command caveat
wrapper, the slash-invocation marker (echo), local-command stdout/stderr,
the platform-rendered slash body, a model-invoked Skill rendering, and
the user-interrupt marker. The predicates here read one record at a time
and let the rest of the package tell the user's sent prompts apart from
that narration; each predicate documents the kind it matches and why it
is or is not user-authored.

Two failure modes need conversation-level context (the ``promptId`` group
of sibling records) and live in ``turns.derive_turns`` instead: a
slash-marker whose paired rendered body is missing, and the
free-typed-shaped error string (``Unknown command: ...``) Claude Code
emits for a malformed slash invocation.
"""

from __future__ import annotations

from .schema import (
    CONTENT_BLOCK_TEXT,
    CONTENT_BLOCK_TOOL_RESULT,
    RECORD_TYPE_USER,
    Record,
    is_compact_summary_user,
)


def is_user_interrupt_marker(record: Record) -> bool:
    """Return ``True`` for the platform's narration of a user interrupt.

    When the user presses Esc to interrupt a tool execution or a
    streaming response, Claude Code injects a user record with a
    list-text content block carrying ``[Request interrupted by
    user]`` or ``[Request interrupted by user for tool use]``. The
    bracketed marker is platform narration of the interrupt event,
    not a user-authored prompt; the user's actual follow-up
    explanation arrives as a subsequent record. The marker is
    filtered to keep interrupt events from inflating the
    turn-starting prompt population.
    """
    if record.record_type != RECORD_TYPE_USER:
        return False
    message = record.payload.get("message")
    if not isinstance(message, dict):
        return False
    content = message.get("content")
    if not isinstance(content, list):
        return False
    for block in content:
        if not isinstance(block, dict):
            continue
        if block.get("type") != CONTENT_BLOCK_TEXT:
            continue
        text = block.get("text")
        if not isinstance(text, str):
            continue
        head = text.lstrip()
        if head.startswith("[Request interrupted by user"):
            return True
    return False


def is_local_command_caveat(record: Record) -> bool:
    """Return ``True`` for the Claude Code local-command caveat wrapper.

    Before every local slash-command execution Claude Code emits a
    user record with ``isMeta == True`` whose string content begins
    with ``<local-command-caveat>``. The wrapper is bookkeeping: it
    tells the model "the messages below were generated by the user
    while running local commands, do not respond to them", and is
    not a user-authored prompt.
    """
    if record.payload.get("isMeta") is not True:
        return False
    content = _user_record_string_content(record)
    if content is None:
        return False
    return content.lstrip().startswith("<local-command-caveat>")


def is_local_command_output(record: Record) -> bool:
    """Return ``True`` for local-command stdout or stderr records.

    Local-only slash commands (``/model``, ``/effort``, ``/clear``,
    ``/exit`` and similar) emit their output as a user record whose
    string content begins with ``<local-command-stdout>`` or
    ``<local-command-stderr>``. The output never reaches the model
    and is not a user-authored prompt.
    """
    content = _user_record_string_content(record)
    if content is None:
        return False
    head = content.lstrip()
    return head.startswith("<local-command-stdout>") or head.startswith("<local-command-stderr>")


def is_slash_command_marker(record: Record) -> bool:
    """Return ``True`` for the marker record of a user slash invocation.

    A marker is a user record (``isMeta`` absent or False) whose
    string content begins with ``<command-message>`` or
    ``<command-name>``. The marker is the user's slash invocation
    echoed back into the conversation; the platform's expansion of
    the slash command into the prompt body delivered to the model
    arrives as a paired rendered body in the same ``promptId``
    group. This predicate alone does not check whether the rendered
    companion exists; the conversation-level decision lives in
    ``turns.derive_turns``.
    """
    if record.payload.get("isMeta") is True:
        return False
    content = _user_record_string_content(record)
    if content is None:
        return False
    head = content.lstrip()
    return head.startswith("<command-message>") or head.startswith("<command-name>")


def is_slash_command_rendered_body(record: Record) -> bool:
    """Return ``True`` for a platform-rendered slash-command body.

    The platform writes a rendered slash-command body as a user
    record with ``isMeta == True`` and a list content carrying at
    least one ``text`` block. The body covers two distinct cases
    that share this structural shape: the paired companion of a
    user-driven slash marker (the user's invocation expanded for
    delivery to the model) and the rendering of a Skill the model
    itself invoked via the Skill tool. The two cases are
    distinguished by ``sourceToolUseID``; see
    ``is_model_invoked_skill_rendering``.
    """
    if record.record_type != RECORD_TYPE_USER:
        return False
    if record.payload.get("isMeta") is not True:
        return False
    message = record.payload.get("message")
    if not isinstance(message, dict):
        return False
    content = message.get("content")
    if not isinstance(content, list):
        return False
    return any(
        isinstance(block, dict) and block.get("type") == CONTENT_BLOCK_TEXT for block in content
    )


def is_model_invoked_skill_rendering(record: Record) -> bool:
    """Return ``True`` for a rendered Skill body the model itself invoked.

    The Claude Code Skill tool lets the model invoke a Skill via a
    ``tool_use`` block; the platform renders the Skill body and
    injects it into the conversation as a user-side record carrying
    ``sourceToolUseID`` pointing at the originating tool_use. The
    rendering counts as model-driven content rather than a
    user-authored prompt.
    """
    if not is_slash_command_rendered_body(record):
        return False
    return isinstance(record.payload.get("sourceToolUseID"), str)


def is_user_authored_prompt(record: Record) -> bool:
    """Return ``True`` for user records the user authored and sent to the model.

    The user-authored set covers two shapes:

    * A free-typed user message (string content with no bookkeeping
      prefix), which on its own opens a turn.
    * A slash-command marker (string content beginning with
      ``<command-message>`` or ``<command-name>``), which opens a
      turn when its paired rendered body is present in the same
      ``promptId`` group. The marker, not the rendered body, is the
      turn anchor: the marker carries the user's invocation
      including command name and arguments, and feeds the bucket
      classifier directly via the ``<command-name>`` tag.

    Records returned as ``False``:

    * Tool-result returns and compact summaries.
    * Local-command caveats and stdout/stderr.
    * Platform-rendered slash bodies. The marker is the anchor for
      user-paired ones; model-invoked ones are not user-authored
      regardless of pairing.
    * Any record carrying ``sourceToolUseID``: the model itself
      caused the rendering.
    * User-interrupt markers (``[Request interrupted by user]`` and
      its tool-use variant): platform narration of an Esc press,
      not user-authored prompt text.
    * Records flagged ``isMeta: true``: by Claude Code's contract a
      meta record is terminal-only and not delivered to the model,
      so it cannot open an assistant turn. Built-in slash commands
      whose rendered body the platform routes back as a meta user
      record (``/context`` and similar) carry both list-shaped and
      string-shaped content; this guard covers both.

    Group-level guards for the two remaining failure modes (markers
    whose ``promptId`` group has no rendered body, and free-typed
    error strings such as ``Unknown command: ...`` emitted by the
    local parser for a typo'd slash invocation) live in
    ``turns.derive_turns``, which has the conversation-level
    ``promptId`` context this predicate intentionally does not.
    """
    if record.record_type != RECORD_TYPE_USER:
        return False
    if is_compact_summary_user(record):
        return False
    if isinstance(record.payload.get("sourceToolUseID"), str):
        return False
    if is_user_interrupt_marker(record):
        return False
    if record.payload.get("isMeta") is True:
        return False
    message = record.payload.get("message")
    if not isinstance(message, dict):
        return False
    content = message.get("content")
    if isinstance(content, list):
        for block in content:
            if isinstance(block, dict) and block.get("type") == CONTENT_BLOCK_TOOL_RESULT:
                return False
        return True
    if isinstance(content, str):
        if is_local_command_caveat(record):
            return False
        return not is_local_command_output(record)
    return False


def _user_record_string_content(record: Record) -> str | None:
    """Return a user record's string content, or ``None`` when not a string.

    Helper for the bookkeeping-shape predicates that match on a
    string content prefix. List or missing content yields ``None``.
    """
    if record.record_type != RECORD_TYPE_USER:
        return None
    message = record.payload.get("message")
    if not isinstance(message, dict):
        return None
    content = message.get("content")
    return content if isinstance(content, str) else None
